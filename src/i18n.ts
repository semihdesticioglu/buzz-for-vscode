/** Translate a key; {0}, {1}… are replaced with the arguments. Falls back to English. */
export function t(key: StringKey, ...args: (string | number)[]): string {
  const s = (current === 'tr' ? TR[key] : EN[key]) ?? EN[key] ?? key;
  return s.replace(/\{(\d+)\}/g, (_, i: string) => String(args[Number(i)] ?? ''));
}

/** Sorting and upper-casing follow the interface language (Turkish has its own i/İ rules). */
export const collator = (): Intl.Collator => new Intl.Collator(lang() === 'tr' ? 'tr' : 'en');
export const localeUpper = (s: string): string => s.toLocaleUpperCase(lang() === 'tr' ? 'tr-TR' : 'en-US');

/** The `ui.*` strings for the webview, keyed without the prefix. */
export function webviewStrings(): Record<string, string> {
  const src = current === 'tr' ? TR : EN;
  const out: Record<string, string> = {};
  for (const k of Object.keys(EN) as StringKey[]) if (k.startsWith('ui.')) out[k.slice(3)] = src[k];
  return out;
}

export function hasAllTranslations(): boolean {
  return (Object.keys(EN) as StringKey[]).every((k) => typeof TR[k] === 'string' && TR[k].length > 0);
}
