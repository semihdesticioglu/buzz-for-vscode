// UI strings in English and Turkish. Kept free of the vscode module so unit tests can use it.
// The extension sets the active language from the `buzz.language` setting ("auto" follows VS Code).

export type Lang = 'en' | 'tr';

let current: Lang = 'en';

export function setLang(l: Lang): void {
  current = l;
}

export function lang(): Lang {
  return current;
}

/** Resolve the `buzz.language` setting against VS Code's display language. */
export function resolveLang(setting: string | undefined, vscodeLanguage: string): Lang {
  if (setting === 'en' || setting === 'tr') return setting;
  return vscodeLanguage.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

